#!/usr/bin/env bash
# Regenerates Formula/<name>.rb for the latest (or a given) release of a
# Breaktrough tool.
#
# Trust: the formula's SHA-256 values come only from the release's
# checksums.txt, and that file is accepted only after its Sigstore signature
# verifies against the tool's release workflow at the exact tag. No other
# credential or secret is involved.
#
# Usage: bin/update-formula.sh <formula> [vX.Y.Z]   (default: the latest release)
#        formula: lockward | wardmap | dpdpward
# Needs: gh (authenticated via GH_TOKEN for API rate limits), curl, cosign.
#
# Exit codes: 0 formula written (or release not yet signed: skipped with a
# notice, nothing written), 1 error, including a failed signature check.
set -euo pipefail

# formula_config sets repo, class, desc and test_body for a formula.
formula_config() {
  case "$1" in
    lockward)
      repo="Breaktroughf1/lockward"
      class="Lockward"
      desc="Lockfile and policy gate for AI agent skills, MCP servers, hooks and rules"
      test_body='    assert_match "lockward #{version}", shell_output("#{bin}/lockward version")
    system bin/"lockward", "init", "--root", testpath
    assert_path_exists testpath/"lockward.policy.yaml"'
      ;;
    wardmap)
      repo="Breaktroughf1/wardmap"
      class="Wardmap"
      desc="Map which secrets and cloud roles one compromised CI credential can reach"
      test_body='    assert_match "wardmap v#{version}", shell_output("#{bin}/wardmap version")
    assert_match "WM001", shell_output("#{bin}/wardmap rules")'
      ;;
    dpdpward)
      repo="Breaktroughf1/dpdpward"
      class="Dpdpward"
      desc="Map personal data in code for India's DPDP Act: data map, ROPA, safeguards"
      test_body='    assert_match "dpdpward v#{version}", shell_output("#{bin}/dpdpward version")
    assert_match "DP001", shell_output("#{bin}/dpdpward rules")'
      ;;
    peerward)
      repo="Breaktroughf1/peerward"
      class="Peerward"
      desc="Sign, verify, audit and pin A2A Agent Cards; fail CI when a peer drifts"
      test_body='    assert_match "peerward v#{version}", shell_output("#{bin}/peerward version")
    assert_match "PW001", shell_output("#{bin}/peerward rules")'
      ;;
    appward)
      repo="Breaktroughf1/appward"
      class="Appward"
      desc="Find keys and backends shipped in web, Android and iOS apps and their reach"
      test_body='    assert_match "appward v#{version}", shell_output("#{bin}/appward version")
    assert_match "AW001", shell_output("#{bin}/appward rules")'
      ;;
    niyam)
      repo="Breaktroughf1/niyam"
      class="Niyam"
      desc="CERT-In and SEBI CSCRF evidence scanner for cloud, hosts and repositories"
      test_body='    assert_match "niyam v#{version}", shell_output("#{bin}/niyam version")
    assert_match "NY-LOG-001", shell_output("#{bin}/niyam checks")'
      ;;
    lineward)
      repo="Breaktroughf1/lineward"
      class="Lineward"
      desc="Find AI-assisted lines in a pull request and enforce human review on them"
      test_body='    assert_match "lineward v#{version}", shell_output("#{bin}/lineward version")
    system bin/"lineward", "init", "--policy", testpath/"lineward.json"
    assert_path_exists testpath/"lineward.json"'
      ;;
    pramaan)
      repo="Breaktroughf1/pramaan"
      class="Pramaan"
      desc="Second-factor verifier for Indian payment apps: attested device binding"
      test_body='    assert_match "pramaan v#{version}", shell_output("#{bin}/pramaan version")
    assert_match(/\A\h{64}\n\z/, shell_output("#{bin}/pramaan gen-key"))'
      ;;
    *)
      echo "error: unknown formula '$1' (want lockward, wardmap, dpdpward, peerward, appward, niyam, lineward or pramaan)" >&2
      return 1
      ;;
  esac
}

render_formula() {
  local name="$1" version="$2" darwin_arm64="$3" darwin_amd64="$4" linux_arm64="$5" linux_amd64="$6"
  local base="https://github.com/${repo}/releases/download/v${version}"
  cat <<RUBY
# typed: false
# frozen_string_literal: true

# This file is generated by bin/update-formula.sh from the release's
# Sigstore-verified checksums.txt. Do not edit it by hand.
class ${class} < Formula
  desc "${desc}"
  homepage "https://github.com/${repo}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/${name}_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/${name}_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/${name}_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/${name}_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "${name}"
  end

  test do
${test_body}
  end
end
RUBY
}

checksum_for() {
  local file="$1" sums="$2" sum
  sum="$(awk -v f="$file" '$2 == f { print $1 }' "$sums")"
  if ! [[ "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "error: no valid checksum for $file in checksums.txt" >&2
    return 1
  fi
  printf '%s' "$sum"
}

main() {
  local name="${1:?usage: bin/update-formula.sh <formula> [vX.Y.Z]}" tag="${2:-}"
  local repo class desc test_body
  formula_config "$name"
  local formula="Formula/${name}.rb"
  if [[ -z "$tag" ]]; then
    local latest
    if ! latest="$(gh api "repos/${repo}/releases/latest" --jq .tag_name 2>&1)"; then
      # No release published yet: nothing to package. Any other error fails.
      if grep -q "HTTP 404" <<<"$latest"; then
        echo "::notice::${name} has no published release yet; skipping, formula unchanged."
        return 0
      fi
      echo "error: looking up the latest ${name} release: ${latest}" >&2
      return 1
    fi
    tag="$latest"
  fi
  if ! [[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "error: refusing unexpected tag '$tag' (want vX.Y.Z, no pre-releases)" >&2
    return 1
  fi
  # Releases from before signed archives existed carry no signature bundle.
  # Skip them (nothing is written); a bundle that exists must verify.
  local assets
  assets="$(gh api "repos/${repo}/releases/tags/${tag}" --jq '.assets[].name')"
  if ! grep -qx 'checksums.txt.sigstore.json' <<<"$assets"; then
    echo "::notice::${name} ${tag} has no signed checksums (checksums.txt.sigstore.json); skipping, formula unchanged."
    return 0
  fi
  local version="${tag#v}" work
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' RETURN

  for f in checksums.txt checksums.txt.sigstore.json; do
    curl --fail --silent --show-error --location --retry 3 --proto '=https' --tlsv1.2 \
      -o "$work/$f" "https://github.com/${repo}/releases/download/${tag}/$f"
  done
  cosign verify-blob \
    --bundle "$work/checksums.txt.sigstore.json" \
    --certificate-identity "https://github.com/${repo}/.github/workflows/release.yml@refs/tags/${tag}" \
    --certificate-oidc-issuer https://token.actions.githubusercontent.com \
    "$work/checksums.txt"

  local s="$work/checksums.txt"
  render_formula "$name" "$version" \
    "$(checksum_for "${name}_${version}_darwin_arm64.tar.gz" "$s")" \
    "$(checksum_for "${name}_${version}_darwin_amd64.tar.gz" "$s")" \
    "$(checksum_for "${name}_${version}_linux_arm64.tar.gz" "$s")" \
    "$(checksum_for "${name}_${version}_linux_amd64.tar.gz" "$s")" > "$work/${name}.rb"
  mkdir -p "$(dirname "$formula")"
  mv "$work/${name}.rb" "$formula"
  echo "Wrote $formula for ${name} $version (checksums verified with Sigstore)."
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
